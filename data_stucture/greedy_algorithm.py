# Greedy algorithm（貪婪演算法）是一種在每一步選擇中都選擇當前看起來最好的選擇的演算法。換句話說，它不考慮較大的範疇，僅基於當下可得的信息作決定。以下是一些經典的貪婪演算法例子：

# 1. **找零問題 (Coin Change Problem)**：
#    假設你是商店的收銀員，需要給顧客找零，且你希望給出的零錢數目盡可能少。如果你的貨幣系統有 1, 5, 10, 25 美分的硬幣，一個貪婪的策略就是每次都選擇最大的硬幣，直到找齊全部的零錢。

# 2. **分數背包問題 (Fractional Knapsack Problem)**：
#    假如你是一個小偷，背著一個背包準備偷寶物。每件寶物有其重量和價值，背包有一定的承重限制。你希望在不超重的情況下，使得背包中寶物的總價值最大。貪婪的策略是按照單位重量價值（價值/重量）降序排列寶物，然後按此順序盡可能多地放入背包中。

# 3. **活動選擇問題 (Activity Selection Problem)**：
#    你有一系列活動，每個活動都有其開始和結束時間。你的目標是選擇最大數量的互不重疊的活動。貪婪的策略是按照活動的結束時間排序，然後從中選擇結束時間最早的活動，接著選擇與已選擇的活動不衝突的下一個結束時間最早的活動，以此類推。

# 4. **霍夫曼編碼 (Huffman Coding)**：
#    霍夫曼編碼是一種用於數據壓縮的貪婪演算法。給定一個字符集，其中每個字符有相應的出現頻率，目標是為每個字符創建一個二進制編碼，使得整個字符串的總編碼長度最短。貪婪策略是建立一個最小堆（或稱優先隊列），其中包含所有字符和其頻率，然後不斷地從堆中取出兩個最小的元素合併，直到堆中只剩下一個元素為止。

# 這些例子展示了貪婪演算法的多樣性和實用性。然而，也要注意並非所有問題都能用貪婪演算法有效解決，有時貪婪策略可能無法得到最優解。